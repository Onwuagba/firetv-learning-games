// Generates app/src/mapData.ts (offline SVG world map) from Natural Earth 110m via the world-atlas package.
// Usage: npm i --no-save world-atlas@2 topojson-client@3 && node scripts/gen-map.mjs
// world-atlas is ISC licensed; data is Natural Earth (public domain).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const topo = require("topojson-client");
const w = require("world-atlas/countries-110m.json");
const K = 4, TOP = 84, BOT = -58;
const px = (lon) => Math.round((lon + 180) * K), py = (lat) => Math.round((TOP - lat) * K);
const fc = topo.feature(w, w.objects.countries);
const out = [];
for (const f of fc.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = "", best = null;
  for (const poly of polys) {
    const ring = poly[0].map(([lo, la]) => [px(lo), py(Math.max(BOT, la))]);
    const pts = ring.filter((p, i) => i === 0 || p[0] !== ring[i - 1][0] || p[1] !== ring[i - 1][1]);
    if (pts.length < 3) continue;
    d += "M" + pts.map((p) => p.join(" ")).join("L") + "Z";
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    const area = (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys));
    if (!best || area > best.area) best = { area, cx: Math.round((Math.max(...xs) + Math.min(...xs)) / 2), cy: Math.round((Math.max(...ys) + Math.min(...ys)) / 2) };
  }
  if (best) out.push({ name: f.properties.name, d, cx: best.cx, cy: best.cy });
}
const W = 360 * K, H = (TOP - BOT) * K;
writeFileSync(new URL("../app/src/mapData.ts", import.meta.url),
`// GENERATED by scripts/gen-map.mjs from Natural Earth 110m (public domain) via world-atlas. Do not edit.
export const MAP_W = ${W};
export const MAP_H = ${H};
export interface MapCountry { name: string; d: string; cx: number; cy: number }
export const MAP_COUNTRIES: MapCountry[] = ${JSON.stringify(out)};
`);
console.log(out.length, "countries");
